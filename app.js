// In-memory storage (resets on page refresh unless synced to GitHub)
function saveToStorage(autoSave = false) {
    const fields = {};
    document.querySelectorAll('.editable-card').forEach(card => {
        const field = card.dataset.field;
        const valueEl = card.querySelector('.editable');
        if (valueEl && field) {
            fields[field] = valueEl.innerHTML;
        }
    });
    
    const dimensionData = [];
    document.querySelectorAll('.dim-input').forEach(input => {
        const field = input.dataset.field;
        if (field) {
            const [rowIndex, dataType] = field.split('-');
            dimensionData[rowIndex] = dimensionData[rowIndex] || {};
            dimensionData[rowIndex][dataType] = input.value;
        }
    });
    document.querySelectorAll('.dim-status').forEach(select => {
        const field = select.dataset.field;
        if (field) {
            const [rowIndex] = field.split('-');
            dimensionData[rowIndex] = dimensionData[rowIndex] || {};
            dimensionData[rowIndex]['status'] = select.value;
        }
    });
    
    const imagesObj = {};
    uploadedImages.forEach((value, key) => {
        imagesObj[key] = value;
    });
    
    window.SAVED_DASHBOARD_FIELDS = fields;
    window.SAVED_DIMENSION_DATA = dimensionData;

    // Auto-save to GitHub Gist (debounced) - works automatically now
    if (autoSave) {
        clearTimeout(autoSaveTimer);
        autoSaveTimer = setTimeout(() => {
            const dataToSave = {
                dashboardFields: fields,
                dimensionData: dimensionData,
                images: imagesObj
            };
            saveToGist(dataToSave).catch(err => {
                console.log('Auto-save to Gist failed:', err.message);
            });
        }, 500); // 500ms debounce
    }
}

async function saveToGist(data) {
    const token = GITHUB_TOKEN; // Use hardcoded token
    
    if (!token || !GIST_ID) {
        throw new Error('GitHub token or Gist ID not configured - see app.js');
    }
    
    const response = await fetch(`https://api.github.com/gists/${GIST_ID}`, {
        headers: {
            'Authorization': `token ${token}`,
            'Accept': 'application/vnd.github.v3+json'
        }
    });
    
    const gist = await response.json();
    const newContent = JSON.stringify(data, null, 2);
    
    await fetch(`https://api.github.com/gists/${GIST_ID}`, {
        method: 'PATCH',
        headers: {
            'Authorization': `token ${token}`,
            'Accept': 'application/vnd.github.v3+json'
        },
        body: JSON.stringify({
            files: {
                [GIST_FILE]: { content: newContent }
            }
        })
    });
}

async function loadFromGist() {
    const token = GITHUB_TOKEN; // Use hardcoded token
    
    if (!token || !GIST_ID) {
        return null;
    }
    
    try {
        const response = await fetch(`https://api.github.com/gists/${GIST_ID}`, {
            headers: {
                'Authorization': `token ${token}`,
                'Accept': 'application/vnd.github.v3+json'
            }
        });
        
        if (!response.ok) return null;
        
        const gist = await response.json();
        const file = gist.files[GIST_FILE];
        
        if (file) {
            return JSON.parse(file.content);
        }
    } catch (e) {
        console.error('Failed to load from Gist:', e);
    }
    
    return null;
}

// Image compression utility for mobile responsiveness
function compressImage(file, maxWidth, maxHeight, quality) {
    return new Promise((resolve, reject) => {
        const img = new Image();
        img.onload = () => {
            const canvas = document.createElement('canvas');
            const scale = Math.min(maxWidth / img.width, maxHeight / img.height, 1);
            const newWidth = Math.floor(img.width * scale);
            const newHeight = Math.floor(img.height * scale);
            
            canvas.width = newWidth;
            canvas.height = newHeight;
            const ctx = canvas.getContext('2d');
            ctx.drawImage(img, 0, 0, newWidth, newHeight);
            
            canvas.toBlob((blob) => {
                if (blob) {
                    const reader = new FileReader();
                    reader.onload = () => resolve(reader.result);
                    reader.readAsDataURL(blob);
                } else {
                    reject(new Error('Canvas to Blob failed'));
                }
            }, 'image/jpeg', quality);
        };
        img.onerror = reject;
        img.src = URL.createObjectURL(file);
    });
}

